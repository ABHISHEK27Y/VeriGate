"""Render a scoped Markdown report only from a validated replay run bundle."""

from __future__ import annotations

import argparse
import csv

from scripts.bundle_directional_replay import ROOT, RUNS
from scripts.verify_evidence_bundle import verify

OUTPUT = ROOT / "docs" / "RESULTS_DIRECTIONAL.md"


def render(run_id: str) -> str:
    path = RUNS / run_id
    manifest = verify(path)
    with (path / "directional_stream_hash.csv").open(newline="", encoding="utf-8") as stream:
        rows = list(csv.DictReader(stream))
    lines = [
        "# Directional factoid replay: local simulation",
        "",
        f"**Run:** `{run_id}` · **Policy:** `{manifest['policy_version']}` · "
        f"**Embedding:** `{manifest['embedding_backend']}`",
        "",
        "The replay serves a concrete recorded reference answer and checks whether its",
        "normalized text appears in the incoming NQ reference list. It uses lexical",
        "hash vectors, a deterministic synthetic upstream answer, 1,500 requests,",
        "three tenants, step-based TTL and LRU. The old pair selection was inspected",
        "during development. These counts do not measure generated-answer truth,",
        "provider cost or a production error rate.",
        "",
        "| Capacity | Policy | Accepted / requests | Mismatches / accepted | Upstream calls |",
        "|---:|---|---:|---:|---:|",
    ]
    for row in rows:
        lines.append(
            f"| {row['capacity_per_tenant']} | {row['system']} | "
            f"{row['accepted_known']} / {row['requests']} | "
            f"{row['accepted_known_false']} / {row['accepted_known']} | "
            f"{row['upstream_calls']} |"
        )
    lines += [
        "",
        "Zero observed reference mismatches at low coverage is not a safety guarantee.",
        "A stored answer can still be incomplete, false or stale. The local model",
        "judge failed validation, and the independent review queue is unlabelled.",
        "",
        f"[CSV](../evaluation/runs/{run_id}/directional_stream_hash.csv) · "
        f"[manifest](../evaluation/runs/{run_id}/manifest.json) · "
        f"[label audit](../evaluation/runs/{run_id}/answer_label_audit.json)",
        "",
        "Generated by `python -m scripts.export_directional_report " + run_id + "`.",
        "Edit the bundle inputs and rerun the exporter; do not edit counts by hand.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("run_id")
    args = parser.parse_args()
    OUTPUT.write_text(render(args.run_id), encoding="utf-8", newline="\n")
    print(OUTPUT)


if __name__ == "__main__":
    main()
