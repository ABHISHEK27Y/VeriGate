"""Build a candid Markdown summary from the generated v2 pair-level CSV."""

from __future__ import annotations

import csv
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "evaluation" / "results" / "v2_pair_metrics.csv"
TARGET = ROOT / "docs" / "RESULTS_V2.md"


def _display(values: list[float]) -> str:
    return f"{statistics.mean(values):.1%}" if values else "undefined"


def main() -> None:
    with SOURCE.open(newline="", encoding="utf-8") as stream:
        rows = list(csv.DictReader(stream))
    grouped: dict[tuple[str, str], list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        grouped[(row["dataset"], row["system"])].append(row)
    lines = [
        "# Pair-label evaluation, generated from `v2_pair_metrics.csv`",
        "",
        "This table is generated by `python scripts/summarize_v2.py`. Five held-out",
        "group-separated splits are evaluated with fixed seeds. The values below are",
        "descriptive means across overlapping test splits; per-split grouped-bootstrap",
        "95% intervals are in the CSV. They are **not** confidence intervals for a",
        "deployed cache or formal false-answer guarantees.",
        "",
        "| Dataset | Policy | Mean coverage | Accepted across splits | Mean false among served |",
        "|---|---|---:|---:|---:|",
    ]
    for (dataset, system), records in sorted(grouped.items()):
        coverage = [float(row["coverage"]) for row in records]
        accepted = sum(int(row["accepted"]) for row in records)
        risk = [
            float(row["false_hit_among_served"]) for row in records if row["false_hit_among_served"]
        ]
        lines.append(
            f"| {dataset} | {system} | {_display(coverage)} | {accepted} | {_display(risk)} |"
        )
    lines.extend(
        [
            "",
            "## Interpretation",
            "",
            "QQP labels identify duplicate questions, PAWS labels identify paraphrase",
            "sentences, and STS-B scores were binarized at the documented threshold.",
            "None contains the stored answer, so a false pair acceptance is a proxy,",
            "not a measured incorrect cached answer. The PAWS mirror sample uses fixed",
            "page offsets recorded under gitignored `data/`.",
            "",
            "The smoke fixture was used to design the historical heuristic. Its",
            "test rows are not independent evidence. Exact mode often accepts no",
            "paraphrase pairs here; undefined risk is not zero risk. No provider cost,",
            "retrieval miss, cache-filling effect, or live latency is measured in this table.",
            "",
            "A trained answer-aware policy and risk target require independently",
            "reviewed answer-reuse labels, which this repository does not yet have.",
            "",
        ]
    )
    TARGET.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(TARGET)


if __name__ == "__main__":
    main()
