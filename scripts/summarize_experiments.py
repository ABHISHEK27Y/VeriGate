"""Generate an honest experimental progress note directly from evaluation CSVs."""

from __future__ import annotations

import csv
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "evaluation" / "results"
TARGET = ROOT / "docs" / "RESULTS_EXPERIMENTAL.md"


def _rows(filename: str) -> list[dict[str, str]]:
    with (RESULTS / filename).open(newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def _mean(rows: list[dict[str, str]], key: str) -> str:
    values = [float(row[key]) for row in rows if row[key] not in {"", "None"}]
    return f"{statistics.mean(values):.1%}" if values else "undefined"


def main() -> None:
    learned = _rows("learned_transfer.csv")
    stream = _rows("stream_proxy.csv")
    risk = _rows("risk_synthetic.csv")
    shifted = _rows("risk_shift_proxy.csv")
    lines = [
        "# Exploratory research results",
        "",
        "Generated by `python scripts/summarize_experiments.py` from the CSVs in",
        "`evaluation/results/`. These are **query-pair proxies or synthetic tests**.",
        "No row establishes the correctness of a cached answer.",
        "",
        "## QQP-trained model transfer",
        "",
        "Logistic regression and gradient boosting were fitted on QQP train groups,",
        "isotonic-calibrated on validation groups, and evaluated on disjoint QQP test",
        "groups and other sources. Thresholds matched the heuristic's calibration",
        "coverage, not its test coverage. Means below span five overlapping splits;",
        "per-split bootstrap intervals are in `learned_transfer.csv`.",
        "",
        "| Test source | Model | Mean coverage | Mean false pair acceptance among served |",
        "|---|---|---:|---:|",
    ]
    grouped: dict[tuple[str, str], list[dict[str, str]]] = defaultdict(list)
    for row in learned:
        grouped[(row["test_source"], row["system"])].append(row)
    for (source, system), rows in sorted(grouped.items()):
        lines.append(
            f"| {source} | {system} | {_mean(rows, 'coverage')} | "
            f"{_mean(rows, 'false_hit_among_served')} |"
        )
    lines.extend(
        [
            "",
            "The exported `accept_proxy.json` is hash-checked and marked",
            "`query_pair_proxy`; its loader refuses to treat it as a reviewed",
            "answer-reuse model. PAWS transfer is poor, so this is not evidence of",
            "a dependable semantic answer cache.",
            "",
            "## Chronological cache replay",
            "",
            "Zipf-popular QQP pairs were replayed with cache filling, TTL, LRU eviction,",
            "tenant partitions and real neighbourhood density. A same-pair source label",
            "is known only for that pair; cross-pair matches are `unknown`.",
            "",
            (
                "| Per-tenant capacity | Policy | Requests | Known accepts | "
                "Known false accepts | Unknown accepts | Positive-density lookups |"
            ),
            "|---:|---|---:|---:|---:|---:|---:|",
        ]
    )
    for row in stream:
        lines.append(
            f"| {row['capacity_per_tenant']} | {row['system']} | {row['requests']} | "
            f"{row['accepted_known']} | {row['accepted_known_false']} | "
            f"{row['accepted_unknown']} | {row['positive_density_lookups']} |"
        )
    lines.extend(
        [
            "",
            "These are replayed pair-proxy counts, not correct cached answers,",
            "monetary savings or production latency. The fixed static threshold is the",
            "historical setting; it was not tuned for this replay.",
            "",
            "## Statistical risk control",
            "",
            "The IID synthetic experiment checks the finite-grid Clopper–Pearson",
            "selection procedure. The public QQP-to-PAWS shift experiment uses pair",
            "labels only and cannot test answer-error control.",
            "",
            (
                "| Target | Synthetic runs with nonempty certified selection | "
                "Synthetic true-risk violations | Mean synthetic coverage | "
                "QQP proxy test accepts | PAWS-shift proxy accepts |"
            ),
            "|---:|---:|---:|---:|---:|---:|",
        ]
    )
    for target in sorted({row["epsilon"] for row in risk}, key=float):
        selected = [row for row in risk if row["epsilon"] == target]
        shift_qqp = [row for row in shifted if row["epsilon"] == target and row["source"] == "qqp"]
        shift_paws = [
            row for row in shifted if row["epsilon"] == target and row["source"] == "paws_shift"
        ]
        nonempty = sum(int(row["calibration_accepted"]) > 0 for row in selected)
        violations = sum(row["true_risk_exceeds_target"] == "1" for row in selected)
        lines.append(
            f"| {float(target):.1%} | {nonempty}/{len(selected)} | {violations} | "
            f"{_mean(selected, 'test_coverage')} | "
            f"{sum(int(row['test_accepted']) for row in shift_qqp)} | "
            f"{sum(int(row['test_accepted']) for row in shift_paws)} |"
        )
    lines.extend(
        [
            "",
            "On the public pair proxy the bound selected reject-all at every tested",
            "target. That is a valid conservative outcome, not proof of low deployed",
            "risk or robustness under shift. A formal claim needs IID or another",
            "justified sampling model, independently reviewed answer labels, and",
            "deployment data without material shift.",
            "",
        ]
    )
    TARGET.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(TARGET)


if __name__ == "__main__":
    main()
