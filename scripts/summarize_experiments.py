"""Generate an honest experimental progress note directly from evaluation CSVs."""

from __future__ import annotations

import csv
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "evaluation" / "results"
TARGET = ROOT / "docs" / "RESULTS_EXPERIMENTAL.md"
NEAR_ZERO_MISMATCH = 0.01


def _rows(filename: str) -> list[dict[str, str]]:
    with (RESULTS / filename).open(newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def _mean(rows: list[dict[str, str]], key: str) -> str:
    values = [float(row[key]) for row in rows if row[key] not in {"", "None"}]
    return f"{statistics.mean(values):.1%}" if values else "undefined"


def _judge_metric(row: dict[str, str], key: str) -> tuple[str, str]:
    estimate = row[key]
    lower, upper = row[f"{key}_ci_low"], row[f"{key}_ci_high"]
    if not estimate:
        return "undefined", "undefined"
    if key == "cohen_kappa":
        return f"{float(estimate):.3f}", f"[{float(lower):.3f}, {float(upper):.3f}]"
    return f"{float(estimate):.1%}", f"[{float(lower):.1%}, {float(upper):.1%}]"


def _integer_range(rows: list[dict[str, str]], key: str) -> str:
    values = [int(row[key]) for row in rows]
    low, high = min(values), max(values)
    return f"{low:,}" if low == high else f"{low:,}–{high:,}"


def main() -> None:  # noqa: PLR0915 - one report assembled from source CSVs
    learned = _rows("learned_transfer.csv")
    stream = _rows("stream_proxy.csv")
    risk = _rows("risk_synthetic.csv")
    shifted = _rows("risk_shift_proxy.csv")
    gold = _rows("gold_model.csv")
    gold_paws = _rows("gold_paws_transfer.csv")
    gold_risk_small = _rows("gold_risk_small.csv")
    gold_risk = _rows("gold_risk.csv")
    gold_risk_candidates = _rows("gold_risk_candidates.csv")
    gold_risk_minimum = _rows("gold_risk_min_samples.csv")
    gold_stream = _rows("gold_stream.csv")
    mining = _rows("gold_mining.csv")[0]
    split_sizes = _rows("gold_split_sizes.csv")
    judge = _rows("judge_validation.csv")[0]
    lines = [
        "# Exploratory research results",
        "",
        "Generated by `python scripts/summarize_experiments.py` from the CSVs in",
        "`evaluation/results/`. They include query-pair proxies, synthetic tests,",
        "and NQ oracle-reference-answer matches. No row establishes correctness",
        "of a generated provider answer or production answer reuse.",
        "",
        "## QQP-trained model transfer",
        "",
        "Logistic regression and gradient boosting were fitted on QQP train groups,",
        "isotonic-calibrated on validation groups, and evaluated on disjoint QQP test",
        "groups and other sources. Thresholds matched the heuristic's calibration",
        "coverage, not its test coverage. Means below span five overlapping splits;",
        "per-split bootstrap intervals are in `learned_transfer.csv`.",
        "",
        "| Test source | Model | Mean coverage | Mean false pair acceptance among served |",
        "|---|---|---:|---:|",
    ]
    grouped: dict[tuple[str, str], list[dict[str, str]]] = defaultdict(list)
    for row in learned:
        grouped[(row["test_source"], row["system"])].append(row)
    for (source, system), rows in sorted(grouped.items()):
        lines.append(
            f"| {source} | {system} | {_mean(rows, 'coverage')} | "
            f"{_mean(rows, 'false_hit_among_served')} |"
        )
    lines.extend(
        [
            "",
            "The exported `accept_proxy.json` is hash-checked and marked",
            "`query_pair_proxy`; its loader refuses to treat it as a reviewed",
            "answer-reuse model. PAWS transfer is poor, so this is not evidence of",
            "a dependable semantic answer cache.",
            "",
            "## Chronological cache replay",
            "",
            "Zipf-popular QQP pairs were replayed with cache filling, TTL, LRU eviction,",
            "tenant partitions and real neighbourhood density. A same-pair source label",
            "is known only for that pair; cross-pair matches are `unknown`.",
            "",
            (
                "| Per-tenant capacity | Policy | Requests | Known accepts | "
                "Known false accepts | Unknown accepts | Positive-density lookups |"
            ),
            "|---:|---|---:|---:|---:|---:|---:|",
        ]
    )
    for row in stream:
        lines.append(
            f"| {row['capacity_per_tenant']} | {row['system']} | {row['requests']} | "
            f"{row['accepted_known']} | {row['accepted_known_false']} | "
            f"{row['accepted_unknown']} | {row['positive_density_lookups']} |"
        )
    lines.extend(
        [
            "",
            "These are replayed pair-proxy counts, not correct cached answers,",
            "monetary savings or production latency. The fixed static threshold is the",
            "historical setting; it was not tuned for this replay.",
            "",
            "## Statistical risk control",
            "",
            "The IID synthetic experiment checks the finite-grid Clopper–Pearson",
            "selection procedure. The public QQP-to-PAWS shift experiment uses pair",
            "labels only and cannot test answer-error control.",
            "",
            (
                "| Target | Synthetic runs with nonempty certified selection | "
                "Synthetic true-risk violations | Mean synthetic coverage | "
                "QQP proxy test accepts | PAWS-shift proxy accepts |"
            ),
            "|---:|---:|---:|---:|---:|---:|",
        ]
    )
    for target in sorted({row["epsilon"] for row in risk}, key=float):
        selected = [row for row in risk if row["epsilon"] == target]
        shift_qqp = [row for row in shifted if row["epsilon"] == target and row["source"] == "qqp"]
        shift_paws = [
            row for row in shifted if row["epsilon"] == target and row["source"] == "paws_shift"
        ]
        nonempty = sum(int(row["calibration_accepted"]) > 0 for row in selected)
        violations = sum(row["true_risk_exceeds_target"] == "1" for row in selected)
        lines.append(
            f"| {float(target):.1%} | {nonempty}/{len(selected)} | {violations} | "
            f"{_mean(selected, 'test_coverage')} | "
            f"{sum(int(row['test_accepted']) for row in shift_qqp)} | "
            f"{sum(int(row['test_accepted']) for row in shift_paws)} |"
        )
    lines.extend(
        [
            "",
            "On the public pair proxy the bound selected reject-all at every tested",
            "target. That is a valid conservative outcome, not proof of low deployed",
            "risk or robustness under shift. A formal claim needs IID or another",
            "justified sampling model, independently reviewed answer labels, and",
            "deployment data without material shift.",
            "",
        ]
    )
    lines.extend(
        [
            "## NQ-Open gold-answer-match factoid study",
            "",
            "The expanded miner compares normalized NQ reference-answer aliases",
            "and explicitly proposes number, relation/attribute, and entity-slot",
            "changes before checking MiniLM similarity. A lexical-plus-semantic",
            "fallback also requires shared content words. The type counts are from",
            "`gold_mining.csv`; entity slots are lexical proxies, not NER labels.",
            "",
            (
                "| Selected pairs | Positives | Attribute swaps | Number swaps | "
                "Entity-slot swaps | Lexical + semantic negatives |"
            ),
            "|---:|---:|---:|---:|---:|---:|",
            (
                f"| {int(mining['selected_pairs']):,} | {int(mining['selected_positive']):,} | "
                f"{mining['attribute_swap']} | {mining['number_swap']} | "
                f"{mining['entity_span_swap']} | {int(mining['lexical_semantic']):,} |"
            ),
            "",
            "The oracle cached answer is not a generated answer. Grouped",
            "train/validation/calibration/test splits use five seeds. Per-split",
            "bootstrap intervals and denominators are in `gold_model.csv`.",
            f"Calibration size per seed: {_integer_range(split_sizes, 'cal_n')};",
            f"held-out test size: {_integer_range(split_sizes, 'test_n')}.",
            "Seeds reuse the same mined corpus, so their means are not",
            "independent-sample confidence intervals.",
            "",
            "| Policy | Mean coverage | Mean gold-answer mismatch among served |",
            "|---|---:|---:|",
        ]
    )
    for system in ("static_val_f1", "adaptive_tier1", "learned_with_nli", "learned_without_nli"):
        rows = [row for row in gold if row["system"] == system]
        lines.append(
            f"| {system} | {_mean(rows, 'coverage')} | "
            f"{_mean(rows, 'false_hit_among_served')} |"
        )
    lines.extend(
        [
            "",
            "The learned model uses lexical, entity/number, polarity, and bidirectional",
            "local NLI entailment features. No model is deployed from this study.",
            (
                "The earlier near-zero mismatch "
                + (
                    "persists on the larger mined set."
                    if statistics.mean(
                        float(row["false_hit_among_served"])
                        for row in gold
                        if row["system"] == "static_val_f1"
                    )
                    < NEAR_ZERO_MISMATCH
                    else "does not survive the larger mined set."
                )
            ),
            "",
            "### PAWS transfer (query-pair proxy; separate label type)",
            "",
            "PAWS labels are paraphrase judgments, not cached-answer truth. The",
            "NQ-trained model also sees blank cached-answer features on PAWS, a",
            "material domain shift. These figures are deliberately not pooled with",
            "NQ gold-answer-match results.",
            "",
            "| Policy | Mean coverage | Mean false pair acceptance among served |",
            "|---|---:|---:|",
        ]
    )
    for system in ("static_val_f1", "adaptive_tier1", "learned_with_nli", "learned_without_nli"):
        rows = [row for row in gold_paws if row["system"] == system]
        lines.append(
            f"| {system} | {_mean(rows, 'coverage')} | "
            f"{_mean(rows, 'false_hit_among_served')} |"
        )
    lines.extend(
        [
            "",
            "### Expanded-corpus gold-label risk selection",
            "",
            "The 10-threshold grid was fixed before inspecting calibration labels.",
            "Each threshold uses a one-sided exact binomial upper bound with",
            "Bonferroni-adjusted alpha 0.005. The selected threshold is checked on",
            "the disjoint test partition. Candidate diagnostics are in",
            "`gold_risk_candidates.csv`; selected decisions are in `gold_risk.csv`.",
            "",
            (
                "| Error target | Nonempty selected seeds | Mean test coverage | "
                "Test mismatches / accepts | Zero-error minimum accepted calibration pairs |"
            ),
            "|---:|---:|---:|---:|---:|",
        ]
    )
    for minimum in gold_risk_minimum:
        target = minimum["epsilon"]
        rows = [row for row in gold_risk if row["epsilon"] == target]
        nonempty = sum(int(row["calibration_accepted"]) > 0 for row in rows)
        errors = sum(int(row["test_errors"]) for row in rows)
        accepts = sum(int(row["test_accepted"]) for row in rows)
        mismatch_count = f"{errors}/{accepts}" if accepts else "undefined (0 accepts)"
        lines.append(
            f"| {float(target):.0%} | {nonempty}/{len(rows)} | "
            f"{_mean(rows, 'test_coverage')} | {mismatch_count} | "
            f"{int(minimum['minimum_accepted_if_zero_errors']):,} |"
        )
    nonempty_candidates = [
        row for row in gold_risk_candidates if int(row["calibration_accepted"]) > 0
    ]
    best_bound = min(float(row["upper_bound"]) for row in nonempty_candidates)
    best = min(nonempty_candidates, key=lambda row: float(row["upper_bound"]))
    lines.extend(
        [
            "",
            f"The smallest nonempty candidate upper bound was {best_bound:.1%} "
            f"(seed {best['seed']}, threshold {best['threshold']}, "
            f"{best['calibration_errors']}/{best['calibration_accepted']} "
            "calibration mismatches/accepts).",
            "The minimum-sample column assumes **zero errors**; errors require more",
            "accepted pairs and may make certification impossible on this corpus.",
            "The five seeds overlap in underlying questions, so their pooled",
            "test counts are descriptive rather than an independent CI.",
            "These reference-answer alias labels are correlated within question",
            "groups and cannot certify generated-answer risk in deployment.",
            "",
            "### Prior small-corpus gold-label risk selection",
            "",
            "The table below is from the previous small corpus in",
            "`gold_risk_small.csv`. It is not a risk result on the expanded corpus.",
            "",
            "| Error target | Reject-all seeds | Mean held-out coverage |",
            "|---:|---:|---:|",
        ]
    )
    for target in sorted({row["epsilon"] for row in gold_risk_small}, key=float):
        rows = [row for row in gold_risk_small if row["epsilon"] == target]
        rejected = sum(int(row["test_accepted"]) == 0 for row in rows)
        lines.append(
            f"| {float(target):.0%} | {rejected}/{len(rows)} | {_mean(rows, 'test_coverage')} |"
        )
    lines.extend(
        [
            "",
            "The prior run selected **reject-all at every target in every seed**. Even zero",
            "observed calibration errors cannot certify these strict bounds with",
            "the available accepted sample sizes and grid correction. Coverage is",
            "zero; no nonempty risk claim follows. Oracle alias labels also cannot",
            "support a deployed generated-answer guarantee.",
            "",
            "### Prior small-corpus chronological gold-answer replay",
            "",
            "This table predates the expanded mining run and is retained only as",
            "a historical replay result; it must not be pooled with the new study.",
            "All accepted hits, including cross-pair candidates, have an NQ alias",
            "comparison; `accepted_unknown` is therefore zero in this study.",
            "The replay uses a Zipf request order, TTL, LRU, and tenant partitions.",
            "",
            (
                "| Per-tenant capacity | Policy | Requests | Accepted | "
                "Gold-answer mismatches | Unknown |"
            ),
            "|---:|---|---:|---:|---:|---:|",
        ]
    )
    for row in gold_stream:
        lines.append(
            f"| {row['capacity_per_tenant']} | {row['system']} | {row['requests']} | "
            f"{row['accepted_known']} | {row['accepted_known_false']} | "
            f"{row['accepted_unknown']} |"
        )
    lines.extend(
        [
            "",
            "This measures reference-answer alias matches, not freshness, answer",
            "completeness, provider quality, or production traffic savings.",
            "",
            "## Prior small-corpus local triple judge validation",
            "",
            "This validation also predates the expanded mining run. Item 3 will",
            "fit a new threshold or model and validate on the new split.",
            "The pinned local FLAN-T5-small judge was evaluated on a grouped",
            "NQ held-out split. Abstentions count as NO for the primary metrics.",
            "The values below come from `judge_validation.csv` with row-bootstrap",
            "95% intervals. Undefined precision means no YES prediction.",
            "",
            f"Validation pairs: {judge['n']}; gold positives: {judge['gold_positive']};",
            f"predicted YES: {judge['predicted_positive']}; abstentions: {judge['abstentions']}.",
            "",
            "| Measure | Estimate | 95% bootstrap interval |",
            "|---|---:|---:|",
            "",
            "This judge failed validation: it predicted no reusable answers and",
            "has no value as an automated correctness signal here. The optional",
            "review queue has blank cached answers, so all rows are",
            "ineligible for judging. The shadow sampler is off by default. No",
            "`model_judged` rows were produced; none are counted as gold evidence.",
            "",
        ]
    )
    metric_header = lines.index("| Measure | Estimate | 95% bootstrap interval |")
    for offset, key in enumerate(("accuracy", "precision", "recall", "cohen_kappa"), 2):
        estimate, interval = _judge_metric(judge, key)
        lines.insert(metric_header + offset, f"| {key} | {estimate} | {interval} |")
    TARGET.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(TARGET)


if __name__ == "__main__":
    main()
