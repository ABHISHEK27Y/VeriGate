"""Generate report tables only from recorded evaluation CSV files.

Run after the evaluation scripts. This intentionally does not invent missing results.
"""

from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "evaluation" / "results"
OUTPUT = ROOT / "report" / "generated"


def rows(name: str, required: set[str]) -> list[dict[str, str]]:
    path = RESULTS / name
    with path.open(newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream)
        if not required.issubset(reader.fieldnames or []):
            raise ValueError(f"{path} lacks required columns: {sorted(required)}")
        data = list(reader)
    if not data:
        raise ValueError(f"{path} is empty")
    return data


def escape(value: str) -> str:
    return value.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("%", r"\%")


def percent(value: str | None) -> str:
    return "N/A" if value in (None, "") else f"{float(value) * 100:.1f}\\%"


def millisecond(value: str) -> str:
    return f"{float(value):.2f}"


def table(  # noqa: PLR0913, PLR0917 - each argument maps to one LaTeX table field
    name: str, caption: str, label: str, columns: str, header: list[str], body: list[list[str]]
) -> None:
    lines = [
        "% Generated by scripts/export_report_tables.py; edit the source CSV, not this file.",
        r"\begin{table}[H]",
        r"\centering",
        r"\footnotesize",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        f"\\begin{{tabular}}{{{columns}}}",
        r"\hline",
        " & ".join(header) + r" \\ \hline",
    ]
    lines.extend(" & ".join(row) + r" \\ \hline" for row in body)
    lines.extend([r"\end{tabular}", r"\end{table}", ""])
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / name).write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> None:
    checks = json.loads((RESULTS / "checks.json").read_text(encoding="utf-8"))
    table(
        "checks.tex",
        "Default local pytest run; skipped integration tests require a disposable Redis Stack.",
        "tab:checks",
        "|r|r|r|r|",
        ["Passed", "Skipped", "Failures", "Errors"],
        [[str(checks[key]) for key in ("passed", "skipped", "failures", "errors")]],
    )

    metrics = rows(
        "metrics.csv",
        {
            "system",
            "positive_recall",
            "negative_false_accept_rate",
            "precision",
            "accepted",
            "model_status",
        },
    )
    table(
        "ablation.tex",
        "Candidate-pair smoke fixture. Positive recall and negative acceptance use "
        "different denominators; this is not workload hit rate or monetary savings.",
        "tab:ablation",
        "|l|c|c|c|c|",
        ["System", "Positive recall", "Negative acceptance", "Precision", "Accepted"],
        [
            [
                escape(row["system"]),
                percent(row["positive_recall"]),
                percent(row["negative_false_accept_rate"]),
                percent(row["precision"]) if row["model_status"] == "available" else "N/A",
                row["accepted"],
            ]
            for row in metrics
        ],
    )

    latency = rows("latency.csv", {"stage", "p50_ms", "p95_ms", "p99_ms"})
    table(
        "latency.tex",
        "Recorded stage timings in milliseconds; these are not end-to-end provider latency.",
        "tab:latency",
        "|l|r|r|r|",
        ["Stage", "p50", "p95", "p99"],
        [
            [
                escape(r["stage"]),
                millisecond(r["p50_ms"]),
                millisecond(r["p95_ms"]),
                millisecond(r["p99_ms"]),
            ]
            for r in latency
        ],
    )

    backend = rows("backend_compare.csv", {"cache_size", "inproc_p50_ms", "redisearch_p50_ms"})
    table(
        "backend.tex",
        "Recorded lookup p50 latency in milliseconds; the crossover size was not measured.",
        "tab:backend",
        "|r|r|r|",
        ["Entries", "In-process", "RediSearch"],
        [
            [r["cache_size"], millisecond(r["inproc_p50_ms"]), millisecond(r["redisearch_p50_ms"])]
            for r in backend
        ],
    )

    cascade = rows(
        "cascade.csv", {"threshold", "escalation_rate", "cost_reduction", "quality_retention"}
    )
    selected = [r for r in cascade if r["threshold"] in {"0.0", "0.35", "0.5", "0.7", "1.0"}]
    if not selected:
        raise ValueError("cascade.csv has no selected thresholds")
    table(
        "cascade.tex",
        "Illustrative cascade cost model. Quality retention is hard-label recall, "
        "not judged answer quality.",
        "tab:cascade",
        "|r|r|r|r|",
        ["Threshold", "Escalation", "Simulated cost reduction", "Hard-label recall"],
        [
            [
                r["threshold"],
                percent(r["escalation_rate"]),
                percent(r["cost_reduction"]),
                percent(r["quality_retention"]),
            ]
            for r in selected
        ],
    )

    learned = rows(
        "learned_transfer.csv",
        {"test_source", "system", "coverage", "false_hit_among_served", "label_type"},
    )
    proxy_groups: dict[tuple[str, str], list[dict[str, str]]] = defaultdict(list)
    for row in learned:
        if row["label_type"] != "query_pair_proxy":
            raise ValueError("Unexpected learned-transfer label type")
        if row["test_source"] in {"qqp", "paws"} and row["system"] in {
            "logistic_all",
            "gradient_boosting",
        }:
            proxy_groups[(row["test_source"], row["system"])].append(row)
    table(
        "learned_proxy.tex",
        "Five-seed query-pair proxy transfer; false acceptance is among accepted "
        "pairs, not answers.",
        "tab:learned-proxy",
        "|l|l|r|r|",
        ["Test source", "Model", "Coverage", "False pair acceptance"],
        [
            [
                escape(source),
                escape(system),
                percent(str(mean(float(row["coverage"]) for row in group))),
                percent(str(mean(float(row["false_hit_among_served"]) for row in group))),
            ]
            for (source, system), group in sorted(proxy_groups.items())
        ],
    )

    stream = rows(
        "stream_proxy.csv",
        {
            "capacity_per_tenant",
            "system",
            "accepted_known",
            "accepted_known_false",
            "accepted_unknown",
        },
    )
    table(
        "stream_proxy.tex",
        "Chronological QQP pair-proxy replay; unknown cross-pair outcomes are not "
        "counted as correct.",
        "tab:stream-proxy",
        "|r|l|r|r|r|",
        ["Capacity", "Policy", "Known accepts", "Known false", "Unknown accepts"],
        [
            [
                row["capacity_per_tenant"],
                escape(row["system"]),
                row["accepted_known"],
                row["accepted_known_false"],
                row["accepted_unknown"],
            ]
            for row in stream
        ],
    )

    risk = rows("risk_synthetic.csv", {"epsilon", "threshold", "true_risk_exceeds_target"})
    risk_groups: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in risk:
        risk_groups[row["epsilon"]].append(row)
    table(
        "risk_synthetic.tex",
        "Synthetic IID bound exercise; reject-all runs have no defined conditional risk.",
        "tab:risk-synthetic",
        "|r|r|r|r|",
        ["Target", "Runs", "Nonempty selections", "True-risk violations"],
        [
            [
                percent(target),
                str(len(group)),
                str(sum(row["threshold"] != "inf" for row in group)),
                str(sum(row["true_risk_exceeds_target"] == "1" for row in group)),
            ]
            for target, group in sorted(risk_groups.items(), key=lambda item: float(item[0]))
        ],
    )

    print(f"Generated eight LaTeX tables in {OUTPUT}")


if __name__ == "__main__":
    main()
